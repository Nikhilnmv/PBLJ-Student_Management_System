-- =====================================================================
--  Student Registration System - Database Schema
--  Database : MySQL 8.0 or newer
--  Run with : mysql -u root -p < database/schema.sql
--
--  This script is SAFE to run more than once: it uses
--  "IF NOT EXISTS", so it never deletes existing data.
-- =====================================================================

-- 1. Create the database (utf8mb4 supports every language and emoji)
CREATE DATABASE IF NOT EXISTS student_registration_db
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

-- 2. Select it, so the tables below are created inside it
USE student_registration_db;

-- ---------------------------------------------------------------------
-- 3. STUDENTS table: one row per registered student
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS students (
    student_id   INT          NOT NULL AUTO_INCREMENT,               -- unique number generated by MySQL
    roll_number  VARCHAR(20)  NOT NULL,                              -- college roll / registration number
    full_name    VARCHAR(100) NOT NULL,
    email        VARCHAR(100) NOT NULL,
    phone        VARCHAR(15)  NOT NULL,                              -- stored as text: keeps leading digits, never used in maths
    gender       VARCHAR(10)  NOT NULL,
    dob          DATE         NOT NULL,                              -- date of birth
    department   VARCHAR(50)  NOT NULL,
    course       VARCHAR(50)  NOT NULL,
    semester     INT          NOT NULL,
    address      TEXT         NOT NULL,
    status       VARCHAR(20)  NOT NULL DEFAULT 'Active',
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,    -- registration date and time

    -- Primary key: uniquely identifies each row
    CONSTRAINT pk_students PRIMARY KEY (student_id),

    -- Unique constraints: the DATABASE itself refuses duplicate roll numbers or emails,
    -- even if two people submit the form at exactly the same moment
    CONSTRAINT uk_students_roll_number UNIQUE (roll_number),
    CONSTRAINT uk_students_email       UNIQUE (email),

    -- Check constraints (enforced by MySQL 8.0.16+): reject impossible values
    CONSTRAINT chk_students_semester CHECK (semester BETWEEN 1 AND 8),
    CONSTRAINT chk_students_status   CHECK (status IN ('Active', 'Inactive')),
    CONSTRAINT chk_students_gender   CHECK (gender IN ('Male', 'Female', 'Other')),

    -- Indexes: speed up the columns we filter and sort by on the admin pages.
    -- (The UNIQUE constraints above automatically create indexes for roll_number and email.)
    INDEX idx_students_department (department),
    INDEX idx_students_semester   (semester),
    INDEX idx_students_status     (status),
    INDEX idx_students_created_at (created_at)
) ENGINE = InnoDB;

-- ---------------------------------------------------------------------
-- 4. ADMIN table: administrator accounts
-- ---------------------------------------------------------------------
-- Admin accounts are NOT inserted here, because that would put a password
-- into a file stored on GitHub. Create the first admin with the setup tool:
--   mvn compile exec:java
-- (see docs/SETUP_AND_EXECUTION.md, "Create the administrator account").
CREATE TABLE IF NOT EXISTS admin (
    admin_id      INT          NOT NULL AUTO_INCREMENT,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,                             -- BCrypt hash, never the real password
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_admin PRIMARY KEY (admin_id),
    CONSTRAINT uk_admin_username UNIQUE (username)
) ENGINE = InnoDB;

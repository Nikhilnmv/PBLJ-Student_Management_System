package com.student.dao;

import com.student.model.Student;
import com.student.model.StudentFilter;
import com.student.util.DBConnection;

import java.sql.Connection;
import java.sql.Date;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLIntegrityConstraintViolationException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * DAO (Data Access Object) for the "students" table.
 *
 * This is the ONLY class that contains SQL for students. Servlets never
 * write SQL themselves; they call methods such as addStudent() or
 * getStudentById(). This keeps database code in one place and makes the
 * servlets short and easy to read.
 *
 * Every query uses a PreparedStatement with ? placeholders. The values are
 * sent to MySQL separately from the SQL text, so input such as
 *     ' OR '1'='1
 * is treated as ordinary text and can never change the SQL command.
 * This is how the application prevents SQL injection.
 *
 * Every Connection, PreparedStatement and ResultSet is opened in a
 * try-with-resources block, so it is closed automatically - even when an
 * exception occurs.
 */
public class StudentDAO {

    /** Columns read by every SELECT, listed once to avoid repeating them. */
    private static final String STUDENT_COLUMNS =
            "student_id, roll_number, full_name, email, phone, gender, dob, "
            + "department, course, semester, address, status, created_at";

    private static final String INSERT_STUDENT_SQL =
            "INSERT INTO students (roll_number, full_name, email, phone, gender, dob, "
            + "department, course, semester, address, status) "
            + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";

    private static final String SELECT_BY_ID_SQL =
            "SELECT " + STUDENT_COLUMNS + " FROM students WHERE student_id = ?";

    private static final String UPDATE_STUDENT_SQL =
            "UPDATE students SET roll_number = ?, full_name = ?, email = ?, phone = ?, gender = ?, dob = ?, "
            + "department = ?, course = ?, semester = ?, address = ?, status = ? "
            + "WHERE student_id = ?";

    private static final String DELETE_STUDENT_SQL = "DELETE FROM students WHERE student_id = ?";

    private static final String UPDATE_STATUS_SQL = "UPDATE students SET status = ? WHERE student_id = ?";

    private static final String ROLL_NUMBER_EXISTS_SQL =
            "SELECT COUNT(*) FROM students WHERE roll_number = ? AND student_id <> ?";

    private static final String EMAIL_EXISTS_SQL =
            "SELECT COUNT(*) FROM students WHERE email = ? AND student_id <> ?";

    // ---- Dashboard statistics ----
    private static final String COUNT_ALL_SQL = "SELECT COUNT(*) FROM students";
    private static final String COUNT_BY_STATUS_SQL = "SELECT COUNT(*) FROM students WHERE status = ?";
    private static final String COUNT_DEPARTMENTS_SQL = "SELECT COUNT(DISTINCT department) FROM students";
    private static final String RECENT_STUDENTS_SQL =
            "SELECT " + STUDENT_COLUMNS + " FROM students ORDER BY created_at DESC, student_id DESC LIMIT ?";
    private static final String DEPARTMENT_COUNTS_SQL =
            "SELECT department, COUNT(*) AS total FROM students "
            + "GROUP BY department ORDER BY total DESC, department ASC";

    // =====================================================================
    // CREATE
    // =====================================================================

    /**
     * Inserts a new student and returns the student_id generated by MySQL.
     *
     * @throws DuplicateStudentException if the roll number or email already exists
     * @throws SQLException              for any other database problem
     */
    public int addStudent(Student student) throws SQLException, DuplicateStudentException {
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(
                     INSERT_STUDENT_SQL, Statement.RETURN_GENERATED_KEYS)) {

            // Fill the 11 ? placeholders, in the same order as the column list
            setStudentParameters(statement, student);
            statement.executeUpdate();

            // Ask MySQL for the AUTO_INCREMENT value it just created
            try (ResultSet keys = statement.getGeneratedKeys()) {
                if (keys.next()) {
                    int newId = keys.getInt(1);
                    student.setStudentId(newId);
                    return newId;
                }
            }
            throw new SQLException("Student was saved but no ID was returned by the database.");

        } catch (SQLIntegrityConstraintViolationException e) {
            throw toDuplicateException(e);
        }
    }

    // =====================================================================
    // READ
    // =====================================================================

    /** Returns the student with the given ID, or null if there is no such student. */
    public Student getStudentById(int studentId) throws SQLException {
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(SELECT_BY_ID_SQL)) {

            statement.setInt(1, studentId);
            try (ResultSet resultSet = statement.executeQuery()) {
                if (resultSet.next()) {
                    return mapRowToStudent(resultSet);
                }
                return null;
            }
        }
    }

    /**
     * Returns ONE PAGE of students that match the filter, newest first.
     *
     * @param offset how many matching rows to skip (0 for the first page)
     * @param limit  maximum number of rows to return (the page size)
     */
    public List<Student> searchStudents(StudentFilter filter, int offset, int limit) throws SQLException {
        List<Object> parameters = new ArrayList<>();
        String sql = "SELECT " + STUDENT_COLUMNS + " FROM students"
                + buildWhereClause(filter, parameters)
                + " ORDER BY created_at DESC, student_id DESC LIMIT ? OFFSET ?";
        parameters.add(limit);
        parameters.add(offset);
        return queryStudents(sql, parameters);
    }

    /**
     * Returns ALL students that match the filter (no paging).
     * Used for the CSV export. This is an OVERLOADED version of the method above.
     */
    public List<Student> searchStudents(StudentFilter filter) throws SQLException {
        List<Object> parameters = new ArrayList<>();
        String sql = "SELECT " + STUDENT_COLUMNS + " FROM students"
                + buildWhereClause(filter, parameters)
                + " ORDER BY created_at DESC, student_id DESC";
        return queryStudents(sql, parameters);
    }

    /** Counts the students that match the filter (needed to calculate the number of pages). */
    public int countStudents(StudentFilter filter) throws SQLException {
        List<Object> parameters = new ArrayList<>();
        String sql = "SELECT COUNT(*) FROM students" + buildWhereClause(filter, parameters);

        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            setParameters(statement, parameters);
            try (ResultSet resultSet = statement.executeQuery()) {
                resultSet.next();
                return resultSet.getInt(1);
            }
        }
    }

    /**
     * True if another student (not the one with excludeStudentId) already uses this roll number.
     * Pass 0 as excludeStudentId when registering a NEW student.
     */
    public boolean isRollNumberTaken(String rollNumber, int excludeStudentId) throws SQLException {
        return countMatches(ROLL_NUMBER_EXISTS_SQL, rollNumber, excludeStudentId) > 0;
    }

    /** True if another student (not the one with excludeStudentId) already uses this email. */
    public boolean isEmailTaken(String email, int excludeStudentId) throws SQLException {
        return countMatches(EMAIL_EXISTS_SQL, email, excludeStudentId) > 0;
    }

    // =====================================================================
    // UPDATE
    // =====================================================================

    /**
     * Saves changes to an existing student.
     *
     * @return true if a row was updated, false if the student does not exist
     */
    public boolean updateStudent(Student student) throws SQLException, DuplicateStudentException {
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(UPDATE_STUDENT_SQL)) {

            setStudentParameters(statement, student);   // placeholders 1-11
            statement.setInt(12, student.getStudentId()); // WHERE student_id = ?
            return statement.executeUpdate() > 0;

        } catch (SQLIntegrityConstraintViolationException e) {
            throw toDuplicateException(e);
        }
    }

    /** Changes only the status column ("Active" or "Inactive"). */
    public boolean updateStatus(int studentId, String status) throws SQLException {
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(UPDATE_STATUS_SQL)) {

            statement.setString(1, status);
            statement.setInt(2, studentId);
            return statement.executeUpdate() > 0;
        }
    }

    // =====================================================================
    // DELETE
    // =====================================================================

    /** Permanently deletes a student. Returns false if the student did not exist. */
    public boolean deleteStudent(int studentId) throws SQLException {
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(DELETE_STUDENT_SQL)) {

            statement.setInt(1, studentId);
            return statement.executeUpdate() > 0;
        }
    }

    // =====================================================================
    // DASHBOARD STATISTICS
    // =====================================================================

    /** Total number of registered students. */
    public int countAllStudents() throws SQLException {
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(COUNT_ALL_SQL);
             ResultSet resultSet = statement.executeQuery()) {
            resultSet.next();
            return resultSet.getInt(1);
        }
    }

    /** Number of students with the given status ("Active" or "Inactive"). */
    public int countStudentsByStatus(String status) throws SQLException {
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(COUNT_BY_STATUS_SQL)) {
            statement.setString(1, status);
            try (ResultSet resultSet = statement.executeQuery()) {
                resultSet.next();
                return resultSet.getInt(1);
            }
        }
    }

    /** Number of different departments that have at least one registered student. */
    public int countDepartments() throws SQLException {
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(COUNT_DEPARTMENTS_SQL);
             ResultSet resultSet = statement.executeQuery()) {
            resultSet.next();
            return resultSet.getInt(1);
        }
    }

    /** The most recently registered students (newest first). */
    public List<Student> getRecentStudents(int limit) throws SQLException {
        List<Object> parameters = new ArrayList<>();
        parameters.add(limit);
        return queryStudents(RECENT_STUDENTS_SQL, parameters);
    }

    /**
     * Number of students in each department, largest first.
     * Uses GROUP BY. A LinkedHashMap keeps the order returned by SQL.
     */
    public Map<String, Integer> getDepartmentCounts() throws SQLException {
        Map<String, Integer> counts = new LinkedHashMap<>();
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(DEPARTMENT_COUNTS_SQL);
             ResultSet resultSet = statement.executeQuery()) {
            while (resultSet.next()) {
                counts.put(resultSet.getString("department"), resultSet.getInt("total"));
            }
        }
        return counts;
    }

    // =====================================================================
    // PRIVATE HELPER METHODS
    // =====================================================================

    /**
     * Builds the WHERE part of the search query from the filter.
     *
     * Only the SQL TEXT is built here, always with ? placeholders. The actual
     * values typed by the admin are added to the parameters list and bound
     * later with PreparedStatement, so the search stays safe from SQL injection.
     */
    private String buildWhereClause(StudentFilter filter, List<Object> parameters) {
        StringBuilder where = new StringBuilder(" WHERE 1 = 1"); // always true; makes adding "AND ..." easy

        if (filter != null) {
            if (filter.getKeyword() != null && !filter.getKeyword().isBlank()) {
                where.append(" AND (full_name LIKE ? OR roll_number LIKE ? OR email LIKE ?)");
                String pattern = "%" + escapeLikeWildcards(filter.getKeyword().trim()) + "%";
                parameters.add(pattern);
                parameters.add(pattern);
                parameters.add(pattern);
            }
            if (filter.getDepartment() != null && !filter.getDepartment().isBlank()) {
                where.append(" AND department = ?");
                parameters.add(filter.getDepartment());
            }
            if (filter.getSemester() != null) {
                where.append(" AND semester = ?");
                parameters.add(filter.getSemester());
            }
            if (filter.getStatus() != null && !filter.getStatus().isBlank()) {
                where.append(" AND status = ?");
                parameters.add(filter.getStatus());
            }
        }
        return where.toString();
    }

    /**
     * In SQL LIKE, '%' and '_' are wildcards. If the admin searches for a
     * literal "_" we escape it with a backslash so it matches only "_".
     */
    private String escapeLikeWildcards(String text) {
        return text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_");
    }

    /** Runs a SELECT that returns student rows and converts them to a List of Student objects. */
    private List<Student> queryStudents(String sql, List<Object> parameters) throws SQLException {
        List<Student> students = new ArrayList<>();
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            setParameters(statement, parameters);
            try (ResultSet resultSet = statement.executeQuery()) {
                while (resultSet.next()) {           // move to the next row until there are no more
                    students.add(mapRowToStudent(resultSet));
                }
            }
        }
        return students;
    }

    /** Binds a list of values to the ? placeholders (1, 2, 3, ...) of a statement. */
    private void setParameters(PreparedStatement statement, List<Object> parameters) throws SQLException {
        for (int i = 0; i < parameters.size(); i++) {
            Object value = parameters.get(i);
            int position = i + 1;  // JDBC placeholders start at 1, not 0
            if (value instanceof Integer) {
                statement.setInt(position, (Integer) value);
            } else {
                statement.setString(position, String.valueOf(value));
            }
        }
    }

    /** Fills placeholders 1-11 with the student's details (shared by INSERT and UPDATE). */
    private void setStudentParameters(PreparedStatement statement, Student student) throws SQLException {
        statement.setString(1, student.getRollNumber());
        statement.setString(2, student.getFullName());
        statement.setString(3, student.getEmail());
        statement.setString(4, student.getPhone());
        statement.setString(5, student.getGender());
        statement.setDate(6, Date.valueOf(student.getDob()));  // LocalDate -> java.sql.Date
        statement.setString(7, student.getDepartment());
        statement.setString(8, student.getCourse());
        statement.setInt(9, student.getSemester());
        statement.setString(10, student.getAddress());
        statement.setString(11, student.getStatus());
    }

    /** Converts the CURRENT row of a ResultSet into a Student object. */
    private Student mapRowToStudent(ResultSet resultSet) throws SQLException {
        Student student = new Student();
        student.setStudentId(resultSet.getInt("student_id"));
        student.setRollNumber(resultSet.getString("roll_number"));
        student.setFullName(resultSet.getString("full_name"));
        student.setEmail(resultSet.getString("email"));
        student.setPhone(resultSet.getString("phone"));
        student.setGender(resultSet.getString("gender"));

        Date dob = resultSet.getDate("dob");
        student.setDob(dob == null ? null : dob.toLocalDate());

        student.setDepartment(resultSet.getString("department"));
        student.setCourse(resultSet.getString("course"));
        student.setSemester(resultSet.getInt("semester"));
        student.setAddress(resultSet.getString("address"));
        student.setStatus(resultSet.getString("status"));

        Timestamp createdAt = resultSet.getTimestamp("created_at");
        student.setCreatedAt(createdAt == null ? null : createdAt.toLocalDateTime());
        return student;
    }

    /** Runs one of the "SELECT COUNT(*) ... WHERE x = ? AND student_id <> ?" queries. */
    private int countMatches(String sql, String value, int excludeStudentId) throws SQLException {
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setString(1, value);
            statement.setInt(2, excludeStudentId);
            try (ResultSet resultSet = statement.executeQuery()) {
                resultSet.next();
                return resultSet.getInt(1);
            }
        }
    }

    /**
     * MySQL reports a broken UNIQUE constraint with a message such as:
     *   Duplicate entry '23CSE001' for key 'students.uk_students_roll_number'
     * We look at the constraint name to tell the user WHICH field is duplicated.
     */
    private DuplicateStudentException toDuplicateException(SQLIntegrityConstraintViolationException e) {
        String message = e.getMessage() == null ? "" : e.getMessage();
        if (message.contains("uk_students_roll_number")) {
            return new DuplicateStudentException("rollNumber",
                    "This roll number is already registered.", e);
        }
        if (message.contains("uk_students_email")) {
            return new DuplicateStudentException("email",
                    "This email address is already registered.", e);
        }
        return new DuplicateStudentException("general",
                "These details conflict with an existing student record.", e);
    }
}

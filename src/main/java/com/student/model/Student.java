package com.student.model;

import java.io.Serializable;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.Period;
import java.time.format.DateTimeFormatter;

/**
 * MODEL class: represents ONE student (one row of the "students" table).
 *
 * This is a plain Java class that only holds data. It demonstrates
 * ENCAPSULATION: every field is private, and other classes read or change
 * the values only through public getter and setter methods.
 *
 * Objects of this class travel between the layers of the application:
 *   JSP form  ->  Servlet (creates a Student)  ->  StudentDAO (saves it to MySQL)
 *   MySQL     ->  StudentDAO (builds a Student) ->  Servlet  ->  JSP (displays it)
 */
public class Student implements Serializable {

    private static final long serialVersionUID = 1L;

    /** Prefix used when showing the student's registration ID, e.g. SRS-00012. */
    public static final String REGISTRATION_ID_PREFIX = "SRS-";

    /** Default status of a newly registered student. */
    public static final String STATUS_ACTIVE = "Active";
    public static final String STATUS_INACTIVE = "Inactive";

    private static final DateTimeFormatter DATE_FORMAT = DateTimeFormatter.ofPattern("dd MMM yyyy");
    private static final DateTimeFormatter DATE_TIME_FORMAT = DateTimeFormatter.ofPattern("dd MMM yyyy, hh:mm a");

    // ----- Fields: one for each column of the students table -----
    private int studentId;            // student_id  (generated by MySQL AUTO_INCREMENT)
    private String rollNumber;        // roll_number
    private String fullName;          // full_name
    private String email;             // email
    private String phone;             // phone
    private String gender;            // gender
    private LocalDate dob;            // dob (date of birth)
    private String department;        // department
    private String course;            // course
    private int semester;             // semester
    private String address;           // address
    private String status;            // status ("Active" or "Inactive")
    private LocalDateTime createdAt;  // created_at (registration date and time)

    /** No-argument constructor: creates an empty student whose status is Active. */
    public Student() {
        this.status = STATUS_ACTIVE;
    }

    /**
     * Constructor with all the details a student types into the registration form.
     * (student_id and created_at are filled in later by the database.)
     */
    public Student(String rollNumber, String fullName, String email, String phone, String gender,
                   LocalDate dob, String department, String course, int semester, String address) {
        this();  // calls the no-argument constructor above, so status = Active
        this.rollNumber = rollNumber;
        this.fullName = fullName;
        this.email = email;
        this.phone = phone;
        this.gender = gender;
        this.dob = dob;
        this.department = department;
        this.course = course;
        this.semester = semester;
        this.address = address;
    }

    // ----- Helper methods used by the JSP pages -----

    /**
     * The ID shown to students and admins, e.g. "SRS-00012" for student_id 12.
     * It is calculated from student_id, so it is always unique.
     */
    public String getRegistrationId() {
        return REGISTRATION_ID_PREFIX + String.format("%05d", studentId);
    }

    /** Date of birth formatted for display, e.g. "14 Mar 2005". */
    public String getDobFormatted() {
        return dob == null ? "" : dob.format(DATE_FORMAT);
    }

    /** Date of birth as yyyy-MM-dd, the format an HTML date input expects. */
    public String getDobIso() {
        return dob == null ? "" : dob.toString();
    }

    /** Registration date formatted for display, e.g. "02 Nov 2026, 05:30 PM". */
    public String getCreatedAtFormatted() {
        return createdAt == null ? "" : createdAt.format(DATE_TIME_FORMAT);
    }

    /** Registration date only (no time), e.g. "02 Nov 2026". */
    public String getCreatedDateFormatted() {
        return createdAt == null ? "" : createdAt.format(DATE_FORMAT);
    }

    /** Age in completed years, calculated from the date of birth. */
    public int getAge() {
        return dob == null ? 0 : Period.between(dob, LocalDate.now()).getYears();
    }

    /** True when the student's status is Active (used to choose badge colours). */
    public boolean isActive() {
        return STATUS_ACTIVE.equals(status);
    }

    /** First letters of the first and last name, e.g. "Aarav Mehta" -> "AM" (used for avatars). */
    public String getInitials() {
        if (fullName == null || fullName.isBlank()) {
            return "?";
        }
        String[] parts = fullName.trim().split("\\s+");
        String initials = parts[0].substring(0, 1);
        if (parts.length > 1) {
            initials += parts[parts.length - 1].substring(0, 1);
        }
        return initials.toUpperCase();
    }

    // ----- Getters and setters -----

    public int getStudentId() {
        return studentId;
    }

    public void setStudentId(int studentId) {
        this.studentId = studentId;
    }

    public String getRollNumber() {
        return rollNumber;
    }

    public void setRollNumber(String rollNumber) {
        this.rollNumber = rollNumber;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getGender() {
        return gender;
    }

    public void setGender(String gender) {
        this.gender = gender;
    }

    public LocalDate getDob() {
        return dob;
    }

    public void setDob(LocalDate dob) {
        this.dob = dob;
    }

    public String getDepartment() {
        return department;
    }

    public void setDepartment(String department) {
        this.department = department;
    }

    public String getCourse() {
        return course;
    }

    public void setCourse(String course) {
        this.course = course;
    }

    public int getSemester() {
        return semester;
    }

    public void setSemester(int semester) {
        this.semester = semester;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    @Override
    public String toString() {
        return "Student{id=" + studentId + ", rollNumber='" + rollNumber + "', name='" + fullName + "'}";
    }
}
